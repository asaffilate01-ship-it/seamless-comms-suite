import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('durable reservations enforce roles, scope, quota, idempotency and RLS', async () => {
 const db = new PGlite();
 const A='00000000-0000-4000-8000-000000000001', B='00000000-0000-4000-8000-000000000002', T='00000000-0000-4000-8000-000000000003';
 await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
 CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 GRANT USAGE ON SCHEMA auth TO authenticated;
 CREATE TABLE public.tenants(id uuid PRIMARY KEY);
 CREATE TABLE public.product_catalogue(product_key text PRIMARY KEY);
 CREATE TABLE public.tenant_members(tenant_id uuid,user_id uuid,role text);
 CREATE TABLE public.tenant_products(tenant_id uuid,product_key text,status text);
 CREATE TABLE public.test_entitlement(enabled boolean); INSERT INTO test_entitlement VALUES(true);
 CREATE FUNCTION public.has_tenant_entitlement(uuid,text) RETURNS boolean LANGUAGE sql AS $$ SELECT enabled FROM public.test_entitlement $$;
 GRANT SELECT ON ALL TABLES IN SCHEMA public TO authenticated,service_role;
 INSERT INTO auth.users VALUES('${A}'),('${B}'); INSERT INTO tenants VALUES('${T}');
 INSERT INTO product_catalogue VALUES('kindelo'),('haccora');
 INSERT INTO tenant_members VALUES('${T}','${A}','owner'),('${T}','${B}','viewer');
 INSERT INTO tenant_products VALUES('${T}','kindelo','active');`);
 await db.exec(await readFile(new URL('../../supabase/migrations/20261029215226_perplexity_research.sql',import.meta.url),'utf8'));
 await db.query("INSERT INTO research_allowances VALUES($1,'kindelo',current_date,current_date+30,1,0,true)",[T]);
 let seq=10;
 const reserve=(actor=A, product='kindelo', id=`00000000-0000-4000-8000-${String(seq++).padStart(12,'0')}`, hash='a'.repeat(64))=>db.query('SELECT reserve_research_request($1,$2,$3,$4,$5,$6) AS admitted',[T,product,actor,id,hash,'general']);
 await db.exec('SET ROLE service_role');
 await assert.rejects(()=>reserve(B)); await assert.rejects(()=>reserve(A,'haccora'));
 const id='00000000-0000-4000-8000-000000000020';
 assert.equal((await reserve(A,'kindelo',id)).rows[0].admitted,true);
 assert.equal((await reserve(A,'kindelo',id)).rows[0].admitted,false);
 await assert.rejects(()=>reserve(A,'kindelo',id,'b'.repeat(64)));
 await assert.rejects(()=>reserve());
 await db.exec('RESET ROLE');
 assert.equal((await db.query('SELECT requests_used FROM research_allowances')).rows[0].requests_used,1);
 await db.exec('SET ROLE authenticated');
 await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[A]);
 assert.equal((await db.query('SELECT * FROM research_requests')).rows.length,1);
 await assert.rejects(()=>reserve());
 await assert.rejects(()=>db.exec('UPDATE research_allowances SET requests_used=0'));
 await assert.rejects(()=>db.exec("UPDATE research_requests SET status='completed'"));
 await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",['00000000-0000-4000-8000-000000000099']);
 assert.equal((await db.query('SELECT * FROM research_requests')).rows.length,0);
 await db.exec('RESET ROLE');
 await db.exec("UPDATE research_requests SET expires_at=now()-interval '1 day'");
 await db.exec('SET ROLE authenticated'); await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[A]);
 assert.equal((await db.query('SELECT * FROM research_requests')).rows.length,0);
 await db.exec('RESET ROLE; UPDATE test_entitlement SET enabled=false; SET ROLE service_role');
 await assert.rejects(()=>reserve(A,'kindelo',id));
 await db.exec('RESET ROLE; UPDATE test_entitlement SET enabled=true; UPDATE research_allowances SET requests_used=0; UPDATE tenant_products SET status=\'inactive\'; SET ROLE service_role');
 await assert.rejects(()=>reserve());
 await db.close();
});
